from pydantic import BaseModel, Field, field_validator


class TokenUsage(BaseModel):
    """Token usage information for LLM calls"""
    
    input_tokens: int = Field(
        default=0,
        description="Total input tokens used in this conversation"
    )
    output_tokens: int = Field(
        default=0,
        description="Total output tokens generated in this conversation"
    )
    total_tokens: int = Field(
        default=0,
        description="Total tokens (input + output)"
    )
    
    model_config = {
        "json_schema_extra": {
            "examples": [
                {
                    "input_tokens": 1250,
                    "output_tokens": 420,
                    "total_tokens": 1670
                }
            ]
        }
    }


# =============================================================================
# Image / File Attachments
# =============================================================================

# Maximum total payload size for attachments (20 MB)
MAX_ATTACHMENT_SIZE_BYTES = 20 * 1024 * 1024

# Allowed MIME types for attachments (images + documents)
ALLOWED_ATTACHMENT_TYPES = {
    "image/png",
    "image/jpeg",
    "image/jpg",
    "image/gif",
    "image/webp",
    "application/pdf",
    "application/vnd.openxmlformats-officedocument.wordprocessingml.document",  # .docx
}

# Convenience alias for backward compatibility
ALLOWED_IMAGE_TYPES = ALLOWED_ATTACHMENT_TYPES


class ImageAttachment(BaseModel):
    """A file attachment sent alongside a chat message.
    
    Supports images (png, jpeg, gif, webp) and documents (pdf, docx).
    The file data is base64-encoded and sent inline in the JSON body.
    For the multipart/form-data upload endpoint the backend converts
    the uploaded file into this format internally.
    """
    
    media_type: str = Field(
        ...,
        description="MIME type of the attachment (e.g. image/png, application/pdf)"
    )
    data: str = Field(
        ...,
        description="Base64-encoded file data (no data-URI prefix)"
    )
    filename: Optional[str] = Field(
        default=None,
        description="Original filename (for display purposes only)"
    )
    
    @property
    def is_pdf(self) -> bool:
        return self.media_type == "application/pdf"
    
    @property
    def is_docx(self) -> bool:
        return self.media_type == "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
    
    @property
    def is_document(self) -> bool:
        return self.is_pdf or self.is_docx
    
    @property
    def is_image(self) -> bool:
        return self.media_type.startswith("image/")
    
    @field_validator("media_type")
    @classmethod
    def validate_media_type(cls, v: str) -> str:
        if v not in ALLOWED_ATTACHMENT_TYPES:
            raise ValueError(
                f"Unsupported attachment type '{v}'. "
                f"Allowed: {', '.join(sorted(ALLOWED_ATTACHMENT_TYPES))}"
            )
        return v
    
    @field_validator("data")
    @classmethod
    def validate_data_not_empty(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Image data cannot be empty")
        return v.strip()


class ChatRequest(BaseModel):
    """Request model for sending a chat message"""
    
    conversation_id: str = Field(
        ...,
        description="Conversation ID generated by the client. Must be provided for both new and existing conversations."
    )
    message: str = Field(
        ...,
        min_length=1,
        max_length=10000,
        description="User message to send to the assistant"
    )
    attachments: Optional[List[ImageAttachment]] = Field(
        default=None,
        description="Optional list of image attachments to include with the message"
    )
    metadata: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Optional metadata for the message (e.g., user info, session data)"
    )
    
    @field_validator('message')
    @classmethod
    def validate_message(cls, v: str) -> str:
        """Ensure message is not just whitespace"""
        if not v.strip():
            raise ValueError("Message cannot be empty or whitespace only")
        return v.strip()
    
    @field_validator('attachments')
    @classmethod
    def validate_attachments(cls, v):
        """Limit number of attachments and total size."""
        if v is None:
            return v
        if len(v) > 5:
            raise ValueError("Maximum 5 attachments per message")
        # Rough size check (base64 is ~4/3 of raw bytes)
        import base64
        total_bytes = 0
        for att in v:
            try:
                total_bytes += len(base64.b64decode(att.data))
            except Exception:
                raise ValueError(f"Invalid base64 data for attachment '{att.filename}'")
        if total_bytes > MAX_ATTACHMENT_SIZE_BYTES:
            raise ValueError(
                f"Total attachment size ({total_bytes / 1024 / 1024:.1f} MB) "
                f"exceeds limit ({MAX_ATTACHMENT_SIZE_BYTES / 1024 / 1024:.0f} MB)"
            )
        return v
    
    model_config = {
        "json_schema_extra": {
            "examples": [
                {
                    "conversation_id": "conv_a1b2c3d4e5f6g7h8",
                    "message": "What tools are available?"
                },
                {
                    "conversation_id": "conv_123abc456def789a",
                    "message": "Analyze this P&ID diagram",
                    "attachments": [
                        {
                            "media_type": "image/png",
                            "data": "<base64-encoded-image>",
                            "filename": "pfd_diagram.png"
                        }
                    ],
                    "metadata": {"user_id": "user_456"}
                }
            ]
        }
    }


class EditMessageRequest(BaseModel):
    """Request model for editing a previously sent user message.
    
    Truncates the conversation from the specified message index onward
    and re-processes with the new content.
    """
    
    message_index: int = Field(
        ...,
        ge=0,
        description="Zero-based index of the user message to edit in the conversation history"
    )
    new_content: str = Field(
        ...,
        min_length=1,
        max_length=10000,
        description="The edited message content to replace the original"
    )
    attachments: Optional[List[ImageAttachment]] = Field(
        default=None,
        description="Optional list of attachments to include with the edited message"
    )
    metadata: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Optional metadata (e.g., user_id for tracking)"
    )

    @field_validator('new_content')
    @classmethod
    def validate_new_content(cls, v: str) -> str:
        if not v.strip():
            raise ValueError("Edited message cannot be empty or whitespace only")
        return v.strip()
    
    model_config = {
        "json_schema_extra": {
            "examples": [
                {
                    "message_index": 2,
                    "new_content": "Design a shell and tube heat exchanger for 500 kW"
                }
            ]
        }
    }


class ToolExecution(BaseModel):
    """Tool execution record for chat response"""
    
    tool_name: str = Field(..., description="Name of the tool executed")
    status: Literal["success", "error"] = Field(..., description="Execution status")
    duration_ms: Optional[int] = Field(default=None, description="Execution time in milliseconds")
    summary: Optional[str] = Field(default=None, description="Brief result summary")
    arguments: Optional[Dict[str, Any]] = Field(default=None, description="Arguments passed to the tool")
    result: Optional[Dict[str, Any]] = Field(default=None, description="Full tool result output")


class ChatResponse(BaseModel):
    """Response model after sending a chat message"""
    
    conversation_id: str = Field(
        ...,
        description="Conversation ID for tracking multi-turn chat"
    )
    request_id: str = Field(
        ...,
        description="Unique request ID for tracking this specific message processing"
    )
    status: Literal["processing", "completed", "error"] = Field(
        ...,
        description="Current status of the request"
    )
    message: Optional[str] = Field(
        default=None,
        description="Optional status message (e.g., error details)"
    )
    token_usage: Optional[TokenUsage] = Field(
        default=None,
        description="Token usage statistics for this conversation"
    )
    run_ids: List[str] = Field(
        default_factory=list,
        description="Array of simulation run IDs (newest first, max 10)"
    )
    tool_executions: List[ToolExecution] = Field(
        default_factory=list,
        description="List of tools executed in this request"
    )
    
    model_config = {
        "json_schema_extra": {
            "examples": [
                {
                    "conversation_id": "conv_123abc",
                    "request_id": "req_789xyz",
                    "status": "processing"
                },
                {
                    "conversation_id": "conv_123abc",
                    "request_id": "req_789xyz",
                    "status": "completed",
                    "message": "Here are the available tools for sugar processing...",
                    "token_usage": {
                        "input_tokens": 1250,
                        "output_tokens": 420,
                        "total_tokens": 1670
                    }
                }
            ]
        }
    }


